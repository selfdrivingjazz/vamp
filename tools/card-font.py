#!/usr/bin/env python3
"""Regenerate the note-card glyph atlases used by vamp-core `card` (exploration findings
without an image). Rasterizes DejaVu Sans Mono (Bitstream Vera license, permits embedding)
into grayscale PNG grids (`COLUMNS` cells per row, characters in code-point order) plus
`crates/vamp-core/src/card_font.rs` with the character list and cell metrics. Covers every
character both faces have in the Latin, Greek, Cyrillic, punctuation, currency, letterlike,
arrow and shape blocks; the renderer maps anything else through NFKD or draws '?'.
Needs Pillow, fontTools and the DejaVu fonts (Debian/Ubuntu: fonts-dejavu-core).

    uv run --with pillow --with fonttools tools/card-font.py
"""
import json
import unicodedata
from pathlib import Path

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates/vamp-core/assets"
FONTS = Path("/usr/share/fonts/truetype/dejavu")
FACES = {"regular": ("DejaVuSansMono.ttf", 30), "bold": ("DejaVuSansMono-Bold.ttf", 56)}
COLUMNS = 64
BLOCKS = [
    (0x0020, 0x007E),  # ASCII
    (0x00A0, 0x024F),  # Latin-1 Supplement, Latin Extended-A/B
    (0x0370, 0x03FF),  # Greek
    (0x0400, 0x04FF),  # Cyrillic
    (0x1E00, 0x1EFF),  # Latin Extended Additional (Vietnamese, …)
    (0x2010, 0x205E),  # General Punctuation (dashes, quotes, ellipsis, primes, …)
    (0x20A0, 0x20CF),  # Currency
    (0x2100, 0x214F),  # Letterlike (™, №, ℃, …)
    (0x2190, 0x21FF),  # Arrows
    (0x25A0, 0x25FF),  # Geometric shapes
]
# Not drawable as a cell of their own: marks, format/control characters and separators
# other than the plain space (the renderer folds those to ' ' or drops them).
SKIP = {"Mn", "Me", "Mc", "Cf", "Cc", "Co", "Cn", "Zl", "Zp"}


def chars() -> str:
    maps = [TTFont(str(FONTS / file)).getBestCmap() for file, _ in FACES.values()]
    out = []
    for first, last in BLOCKS:
        for code in range(first, last + 1):
            char = chr(code)
            category = unicodedata.category(char)
            if category in SKIP or (category == "Zs" and char != " "):
                continue
            if all(code in cmap for cmap in maps):
                out.append(char)
    return "".join(out)


def atlas(file: str, size: int, text: str) -> tuple[int, int]:
    font = ImageFont.truetype(str(FONTS / file), size)
    ascent, descent = font.getmetrics()
    width = round(font.getlength("M"))
    height = ascent + descent
    rows = -(-len(text) // COLUMNS)
    image = Image.new("L", (width * COLUMNS, height * rows), 0)
    for i, char in enumerate(text):
        # Clip each glyph to its cell so overhangs never bleed into a neighbour.
        cell = Image.new("L", (width, height), 0)
        ImageDraw.Draw(cell).text((0, 0), char, font=font, fill=255)
        image.paste(cell, ((i % COLUMNS) * width, (i // COLUMNS) * height))
    name = file.removesuffix(".ttf").lower()
    image.save(OUT / f"card-{name}.png", optimize=True)
    return width, height


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    text = chars()
    lines = [
        "// Generated by tools/card-font.py from DejaVu Sans Mono (Bitstream Vera license). Do not edit.",
        "// Characters in code-point order; glyph i sits at cell (i % COLUMNS, i / COLUMNS).",
        f"pub(crate) const CHARS: &str = {json.dumps(text, ensure_ascii=False)};",
        f"pub(crate) const COLUMNS: u32 = {COLUMNS};",
    ]
    for face, (file, size) in FACES.items():
        width, height = atlas(file, size, text)
        name = file.removesuffix(".ttf").lower()
        lines.append(
            f"pub(crate) const {face.upper()}: super::Face = super::Face {{ atlas: include_bytes!(\"../assets/card-{name}.png\"), "
            f"cell_width: {width}, cell_height: {height} }};"
        )
    (ROOT / "crates/vamp-core/src/card_font.rs").write_text("\n".join(lines) + "\n")
    print(f"{len(text)} characters")


if __name__ == "__main__":
    main()
